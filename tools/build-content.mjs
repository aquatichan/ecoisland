// Builds the public question files and the server-only answer key from the
// full course content in content/.
//
//   content/APES/APES_Unit{n}.json                → public/APES/APES_Unit{n}.json (no answers)
//   content/APES_Modules/Unit_n/<lesson>/questions.json → public/... (no answers)
//   content/APES/APES_FRQs.json                   → public/APES/APES_FRQs.json (no rubrics)
//   answers and rubrics                           → worker/generated/content.ts
//
// The browser never receives an answer key or a rubric; the Worker checks
// every answer and grades every FRQ. Run after editing anything in content/:
//
//   pnpm content
//
// test/unit/content.test.ts fails if the generated files are out of date.

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const LETTERS = ["A", "B", "C", "D"];
const letter = (v) => LETTERS.indexOf(String(v ?? "").trim().toUpperCase());
const json = (v) => `${JSON.stringify(v, null, 2)}\n`;

/** "1.10_Energy_Flow" → "L1_10" (matches lessonKey in src/shared/curriculum.ts). */
export function lessonKeyFromFolder(folder) {
  return `L${folder.split("_")[0].replace(/\./g, "_")}`;
}

/**
 * Returns every generated file as { [path relative to root]: contents }.
 * Pure: reads from content/ only, writes nothing.
 */
export function buildContent(root) {
  const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
  const files = {};
  const answers = {};
  const skipped = [];

  // Unit banks.
  for (let n = 1; n <= 9; n++) {
    const src = `content/APES/APES_Unit${n}.json`;
    const out = [];
    read(src).forEach((q, i) => {
      const id = `U${n}_${i}`;
      const answer = letter(q.answer);
      const choices = [q.A, q.B, q.C, q.D];
      if (answer < 0 || !choices.every((c) => typeof c === "string" && c.length > 0) || typeof q.question !== "string") {
        skipped.push(id);
        return;
      }
      answers[id] = answer;
      out.push({ id, question: q.question, difficulty: q.difficulty, A: q.A, B: q.B, C: q.C, D: q.D, ...(q.stimulus ? { stimulus: q.stimulus } : {}) });
    });
    files[`public/APES/APES_Unit${n}.json`] = json(out);
  }

  // Lesson quizzes.
  const modules = join(root, "content/APES_Modules");
  for (const unitDir of readdirSync(modules).sort()) {
    for (const lesson of readdirSync(join(modules, unitDir)).sort()) {
      const rel = `APES_Modules/${unitDir}/${lesson}/questions.json`;
      if (!existsSync(join(root, "content", rel))) continue;
      const key = lessonKeyFromFolder(lesson);
      const out = [];
      read(`content/${rel}`).forEach((q, i) => {
        const id = `${key}_${i}`;
        const answer = letter(q.correct);
        const choices = Array.isArray(q.answers) ? q.answers.slice(0, 4) : [];
        if (answer < 0 || choices.length !== 4 || typeof q.question !== "string") {
          skipped.push(id);
          return;
        }
        answers[id] = answer;
        out.push({ id, question: q.question, answers: choices, ...(q.stimulus ? { stimulus: q.stimulus } : {}) });
      });
      files[`public/${rel}`] = json(out);
    }
  }

  // FRQs: prompts are public, rubrics are not.
  const frqs = read("content/APES/APES_FRQs.json");
  files["public/APES/APES_FRQs.json"] = json(
    frqs.map((f) => ({ ...f, parts: f.parts.map(({ label, prompt, points }) => ({ label, prompt, points })) })),
  );

  const answerLines = Object.entries(answers)
    .map(([id, a]) => `  ${id}: ${a},`)
    .join("\n");
  files["worker/generated/content.ts"] = [
    "// Generated by tools/build-content.mjs from content/. Do not edit by hand;",
    "// run `pnpm content` instead. Server-only: never import this from src/.",
    "",
    'import type { Frq } from "../frq";',
    "",
    "/** Correct choice (0–3) for every question id. */",
    `export const ANSWERS: Readonly<Record<string, number>> = {\n${answerLines}\n};`,
    "",
    "/** Every FRQ with its rubric. */",
    `export const FRQS: readonly Frq[] = ${JSON.stringify(frqs, null, 2)};`,
    "",
  ].join("\n");

  return { files, count: Object.keys(answers).length, skipped };
}

// CLI: write the files.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const { files, count, skipped } = buildContent(root);
  for (const [path, contents] of Object.entries(files)) {
    const full = join(root, path);
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, contents);
  }
  console.log(`content: ${count} questions, ${Object.keys(files).length} files written${skipped.length ? `, ${skipped.length} malformed skipped` : ""}`);
  if (skipped.length) console.log(`  skipped: ${skipped.join(", ")}`);
}
